        )

    /** Epoch day of 1 Muharram for each year in FIRST_YEAR..LAST_YEAR + 1. */
    private val yearStarts: LongArray =
        LongArray(LAST_YEAR - FIRST_YEAR + 2).also { starts ->
            starts[0] = FIRST_EPOCH_DAY
            for (i in 1 until starts.size) {
                starts[i] = starts[i - 1] + yearLength(FIRST_YEAR + i - 1)
            }
        }

    /** Epoch day after 29/30 Dhu al-Hijjah [LAST_YEAR]. */
    val endEpochDayExclusive: Long get() = yearStarts.last()

    fun monthLength(
        year: Int,
        month: Int,
    ): Int = if (monthMasks[year - FIRST_YEAR] and (1 shl (12 - month)) != 0) 30 else 29

    fun yearLength(year: Int): Int = (1..12).sumOf { monthLength(year, it) }

    fun yearStart(year: Int): Long = yearStarts[year - FIRST_YEAR]

    /** Hijri year whose first day is the last one <= [epochDay]; requires the day to be in range. */
    fun yearOf(epochDay: Long): Int {
        var lo = 0
        var hi = yearStarts.size - 2
        while (lo < hi) {
            val mid = (lo + hi + 1) / 2
            if (yearStarts[mid] <= epochDay) lo = mid else hi = mid - 1
        }
        return FIRST_YEAR + lo
    }
}
