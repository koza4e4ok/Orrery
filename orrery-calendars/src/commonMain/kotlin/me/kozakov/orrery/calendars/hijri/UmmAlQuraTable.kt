package me.kozakov.orrery.calendars.hijri

/**
 * Umm al-Qura month lengths for 1300..1600 AH, one 12-bit mask per year: bit 11
 * is Muharram, bit 0 is Dhu al-Hijjah, a set bit means 30 days, a clear bit 29.
 * Encoded from the UMALQURA_MONTHLENGTH table in ICU4J's IslamicCalendar
 * (Unicode License v3, see NOTICE); year starts are cumulative from
 * 1 Muharram 1300 = 1882-11-12.
 */
internal object UmmAlQuraTable {
    const val FIRST_YEAR: Int = 1300
    const val LAST_YEAR: Int = 1600

    /** Epoch day (days since 1970-01-01) of 1 Muharram [FIRST_YEAR]. */
    const val FIRST_EPOCH_DAY: Long = -31826

    private val monthMasks =
