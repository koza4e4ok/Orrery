private fun doubleFloor(value: Double): Double {
    val v = floor(value)
    return if (v < 0) v + 1 else v
}

private fun rad2mrad(value: Double): Double {
    val v = value % (2 * PI)
    return if (v < 0) v + 2 * PI else v
}

private fun worldTimeDiff(year: Double): Double {
    var i = 0
    while (i < 100) {
        if (year < DTS[i + 5] || i == 95) break
        i += 5
    }
    val t1 = (year - DTS[i]) / (DTS[i + 5] - DTS[i]) * 10
    val t2 = t1 * t1
    val t3 = t2 * t1
    return DTS[i + 1] + DTS[i + 2] * t1 + DTS[i + 3] * t2 + DTS[i + 4] * t3
}

private fun atomTimeDiff(julian: Double): Double = worldTimeDiff(julian / 365.2425 + 2000) / 86400.0

/** Port of setFromJulian(jd, UTC = true), date part only. */
internal fun julianToDate(julian: Double): LocalDate {
    var jd = julian - atomTimeDiff(julian - J2000)
    jd += 0.5
    var a = doubleFloor(jd)
    if (a > 2299161) {
        val d = doubleFloor((a - 1867216.25) / 36524.25)
        a += 1 + d - doubleFloor(d / 4)
    }
    a += 1524.0
    var year = doubleFloor((a - 122.1) / 365.25)
    val rest = a - doubleFloor(365.25 * year)
    var month = doubleFloor(rest / 30.6001)
    val day = rest - doubleFloor(month * 30.6001)
    year -= 4716
    month--
    if (month > 12) month -= 12
    if (month <= 2) year++
    return LocalDate(year.toInt(), month.toInt(), day.toInt())
}

private fun periodicSum(
    table: DoubleArray,
    t: Double,
): Double {
    var v = 0.0
    var i = 0
    while (i < table.size) {
        v += table[i] * cos(table[i + 1] + t * table[i + 2])
        i += 3
    }
    return v
}

/** Sun ecliptic [longitude, latitude]; port of earCal without the unused distance terms. */
private fun earthCoord(jd: Double): DoubleArray {
    val t = jd / 365250
    val t1 = t
    val t2 = t1 * t1
    val t3 = t2 * t1
    val t4 = t3 * t1
    val t5 = t4 * t1
    val lon = periodicSum(E10, t) + periodicSum(E11, t) * t1 + periodicSum(E12, t) * t2 +
        periodicSum(E13, t) * t3 + periodicSum(E14, t) * t4 + periodicSum(E15, t) * t5
    val lat = periodicSum(E20, t) + periodicSum(E21, t) * t1
    return doubleArrayOf(rad2mrad(lon), lat)
}

/** Port of addGxc (annual aberration). */
private fun addAberration(
    t: Double,
    zb: DoubleArray,
) {
    val t1 = t / 36525
    val t2 = t1 * t1
    val t3 = t2 * t1
    val t4 = t3 * t1
    val l = GXC_L[0] + GXC_L[1] * t1 + GXC_L[2] * t2 + GXC_L[3] * t3 + GXC_L[4] * t4
    val p = GXC_P[0] + GXC_P[1] * t1 + GXC_P[2] * t2
    val e = GXC_E[0] + GXC_E[1] * t1 + GXC_E[2] * t2
    val dL = l - zb[0]
    val dP = p - zb[0]
    zb[0] -= GXC_K * (cos(dL) - e * cos(dP)) / cos(zb[1])
    zb[1] -= GXC_K * sin(zb[1]) * (sin(dL) - e * sin(dP))
    zb[0] = rad2mrad(zb[0])
}

/** Port of nutation(), longitude component only (obliquity is unused for solar terms). */
private fun nutationLon(time: Double): Double {
    val t = time / 36525
    var lon = 0.0
    val t1 = t
    val t2 = t1 * t1
    val t3 = t2 * t1
    val t4 = t3 * t1
    var i = 0
    while (i < NUT_B.size) {
        val c = NUT_B[i] + NUT_B[i + 1] * t1 + NUT_B[i + 2] * t2 + NUT_B[i + 3] * t3 + NUT_B[i + 4] * t4
        lon += (NUT_B[i + 5] + NUT_B[i + 6] * t / 10) * sin(c)
        i += 9
    }
    return lon / (SECOND_PER_RAD * 10000)
}

/** Port of angleDiff(lx = 0): difference between [angle] and apparent sun longitude at [time]. */
private fun sunAngleDiff(
    time: Double,
    angle: Double,
): Double {
    val sun = earthCoord(time)
    sun[0] += PI
    sun[1] = -sun[1]
    addAberration(time, sun)
    sun[0] += nutationLon(time)
    return rad2mrad(angle - sun[0])
}

/** Port of getTimeFromAngle(t1, angle, lx = 0): J2000 julian day when sun longitude reaches [angleDeg]. */
internal fun timeOfSunLongitude(
    start: Double,
    angleDeg: Double,
): Double {
    var t1 = start
    var t2 = t1 + 360
    var t = 0.0
    val angle = angleDeg * PI / 180
    var v1 = sunAngleDiff(t1, angle)
    var v2 = sunAngleDiff(t2, angle)
    if (v1 < v2) v2 -= 2 * PI
    var k = 1.0
    for (i in 0 until 10) {
        val k2 = (v2 - v1) / (t2 - t1)
        if (abs(k2) > 1e-15) k = k2
        t = t1 - v1 / k
        var v = sunAngleDiff(t, angle)
        if (v > 1) v -= 2 * PI
        if (abs(v) < 1e-8) break
        t1 = t2
        v1 = v2
        t2 = t
        v2 = v
    }
    return t
}
